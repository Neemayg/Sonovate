import type { NextConfig } from "next";

// Security headers. connect-src is limited to the two backends the browser
// talks to, taken from the NEXT_PUBLIC_* values baked in at build time, so a
// production build must be made with the production URLs.
//
// script-src keeps 'unsafe-inline' because Next.js inlines its bootstrap
// scripts; a nonce-based policy would need per-request rendering. 'unsafe-eval'
// and websocket connections are allowed only in development (React dev tools
// and hot reload).
const isDev = process.env.NODE_ENV !== "production";

function origin(url: string | undefined): string | null {
  if (!url) return null;
  try {
    return new URL(url).origin;
  } catch {
    return null;
  }
}

const backends = [origin(process.env.NEXT_PUBLIC_SUPABASE_URL), origin(process.env.NEXT_PUBLIC_INFERENCE_API_URL)].filter(
  (o): o is string => o !== null,
);

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "media-src 'self' blob:",
  "font-src 'self'",
  `connect-src 'self' ${backends.join(" ")}${isDev ? " ws: wss:" : ""}`,
  "frame-ancestors 'none'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  // HSTS only makes sense over https; browsers ignore it on plain http.
  ...(isDev ? [] : [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" }]),
];

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
